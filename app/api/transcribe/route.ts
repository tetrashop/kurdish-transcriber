import { NextRequest, NextResponse } from 'next/server';

export const runtime = 'nodejs';
// حداکثر زمان اجرا برای پلن رایگان Vercel (قابل تنظیم تا 300 ثانیه)
export const maxDuration = 60; 

// یک نقشه ساده در حافظه برای Rate Limiting (برای هر IP)
const rateLimitMap = new Map<string, { count: number; lastReset: number }>();
const RATE_LIMIT_WINDOW = 60 * 1000; // 1 دقیقه
const MAX_REQUESTS_PER_WINDOW = 10; // حداکثر 10 درخواست در دقیقه

function isRateLimited(ip: string): boolean {
  const now = Date.now();
  const record = rateLimitMap.get(ip);

  if (!record || now - record.lastReset > RATE_LIMIT_WINDOW) {
    rateLimitMap.set(ip, { count: 1, lastReset: now });
    return false;
  }

  if (record.count >= MAX_REQUESTS_PER_WINDOW) {
    return true;
  }

  record.count++;
  return false;
}

export async function POST(req: NextRequest) {
  // ۱. بررسی Rate Limit
  const ip = req.headers.get('x-forwarded-for') || 'unknown';
  if (isRateLimited(ip)) {
    return NextResponse.json(
      { error: 'تعداد درخواست‌ها زیاد است. لطفاً یک دقیقه صبر کنید.' },
      { status: 429 }
    );
  }

  const apiKey = process.env.GROQ_API_KEY;
  if (!apiKey) {
    return NextResponse.json({ error: 'خطای تنظیمات سرور: کلید API موجود نیست.' }, { status: 500 });
  }

  const form = await req.formData();
  const file = form.get('file');
  if (!(file instanceof Blob)) {
    return NextResponse.json({ error: 'فایل صوتی دریافت نشد.' }, { status: 400 });
  }

  try {
    // ۲. تبدیل صدا به متن (بدون پرامپت تا مدل آن را تکرار نکند)
    const upstream = new FormData();
    upstream.append('file', file, 'chunk.wav');
    upstream.append('model', 'whisper-large-v3');
    upstream.append('language', 'fa'); // استفاده از fa به عنوان نزدیک‌ترین زبان
    upstream.append('response_format', 'json');
    upstream.append('temperature', '0');

    const sttRes = await fetch('https://api.groq.com/openai/v1/audio/transcriptions', {
      method: 'POST',
      headers: { Authorization: `Bearer ${apiKey}` },
      body: upstream,
    });

    if (!sttRes.ok) {
        throw new Error(`خطای سرویس تبدیل گفتار: ${sttRes.status}`);
    }
    const sttData = await sttRes.json();
    let originalText = sttData.text?.trim() || '';

    // فیلتر کردن توهم‌زنی‌های رایج Whisper (کلمات پرتکرار در سکوت)
    const hallucinations = ['موسیقی', 'Music', 'زیرنویس', 'ترجمه', 'Thank you', 'تکایە بە زمانی'];
    if (hallucinations.some(h => originalText.includes(h)) && originalText.length < 40) {
        return NextResponse.json({ kurdish: '', persian: '' });
    }

    if (!originalText) return NextResponse.json({ kurdish: '', persian: '' });

    // ۳. ترجمه با مدل جدید و پرامپت ساده (بدون JSON برای جلوگیری از خطا)
    const llmRes = await fetch('https://api.groq.com/openai/v1/chat/completions', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${apiKey}`,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        model: 'openai/gpt-oss-20b', // مدل جایگزین و پایدار
        messages: [
          {
            role: 'system',
            content: `You are a Kurdish (Sorani) to Persian translator. The user will provide a text generated by speech recognition which might have phonetic errors or be a mix of Kurdish and Persian. First, infer the intended Kurdish text. Second, translate it to fluent Persian. Output EXACTLY in this format:\nKURDISH: [corrected kurdish text]\nPERSIAN: [persian translation]`
          },
          { role: 'user', content: originalText }
        ],
        temperature: 0.1,
      }),
    });

    if (!llmRes.ok) {
        const errText = await llmRes.text();
        return NextResponse.json({ kurdish: originalText, persian: `خطای ترجمه: ${errText.slice(0, 50)}` });
    }

    const llmData = await llmRes.json();
    const content = llmData.choices[0].message.content;

    // استخراج متن کردی و فارسی از خروجی
    let kurdishText = originalText;
    let persianText = 'ترجمه انجام نشد';

    if (content.includes('KURDISH:') && content.includes('PERSIAN:')) {
        const parts = content.split('PERSIAN:');
        kurdishText = parts[0].replace('KURDISH:', '').trim();
        persianText = parts[1].trim();
    } else {
        persianText = content.replace(/\n/g, ' ').trim();
    }

    return NextResponse.json({ kurdish: kurdishText, persian: persianText });

  } catch (e: any) {
    return NextResponse.json({ error: `خطای شبکه: ${e.message}` }, { status: 502 });
  }
}
