import { NextRequest, NextResponse } from 'next/server';

export const runtime = 'nodejs';
export const maxDuration = 60;

const rateLimitMap = new Map<string, { count: number; lastReset: number }>();
const RATE_LIMIT_WINDOW = 60 * 1000;
const MAX_REQUESTS_PER_WINDOW = 10;

function isRateLimited(ip: string): boolean {
  const now = Date.now();
  const record = rateLimitMap.get(ip);
  if (!record || now - record.lastReset > RATE_LIMIT_WINDOW) {
    rateLimitMap.set(ip, { count: 1, lastReset: now });
    return false;
  }
  if (record.count >= MAX_REQUESTS_PER_WINDOW) return true;
  record.count++;
  return false;
}

export async function POST(req: NextRequest) {
  const ip = req.headers.get('x-forwarded-for') || 'unknown';
  if (isRateLimited(ip)) {
    return NextResponse.json({ error: 'محدودیت درخواست (Rate Limit)' }, { status: 429 });
  }

  const apiKey = process.env.GROQ_API_KEY;
  if (!apiKey) return NextResponse.json({ error: 'GROQ_API_KEY missing' }, { status: 500 });

  const form = await req.formData();
  const file = form.get('file');
  if (!(file instanceof Blob)) return NextResponse.json({ error: 'audio file missing' }, { status: 400 });

  try {
    const upstream = new FormData();
    upstream.append('file', file, 'chunk.wav');
    upstream.append('model', 'whisper-large-v3');
    upstream.append('language', 'fa'); 
    upstream.append('response_format', 'json');
    upstream.append('temperature', '0');

    const sttRes = await fetch('https://api.groq.com/openai/v1/audio/transcriptions', {
      method: 'POST',
      headers: { Authorization: `Bearer ${apiKey}` },
      body: upstream,
    });

    if (!sttRes.ok) throw new Error(`STT Error: ${sttRes.status}`);
    const sttData = await sttRes.json();
    let originalText = sttData.text?.trim() || '';

    const hallucinations = ['موسیقی', 'Music', 'زیرنویس', 'ترجمه', 'Thank you', 'تکایە بە زمانی'];
    if (hallucinations.some(h => originalText.includes(h)) && originalText.length < 40) {
        return NextResponse.json({ kurdish: '', persian: '' }); 
    }

    if (!originalText) return NextResponse.json({ kurdish: '', persian: '' });

    const llmRes = await fetch('https://api.groq.com/openai/v1/chat/completions', {
      method: 'POST',
      headers: { 
        Authorization: `Bearer ${apiKey}`,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        model: 'llama-3.1-8b-instant',
        messages: [
          { 
            role: 'system', 
            content: 'You are a Kurdish (Sorani) to Persian translator. The user will provide a text generated by speech recognition which might have phonetic errors. First, correct it to standard Kurdish. Second, translate it to fluent Persian. Output EXACTLY in this format:\nKURDISH: [corrected kurdish text]\nPERSIAN: [persian translation]' 
          },
          { role: 'user', content: originalText }
        ],
        temperature: 0.1,
      }),
    });

    if (!llmRes.ok) {
        return NextResponse.json({ kurdish: originalText, persian: 'ترجمه در دسترس نیست' });
    }

    const llmData = await llmRes.json();
    const content = llmData.choices[0].message.content;
    
    let kurdishText = originalText;
    let persianText = 'ترجمه نشد';
    
    if (content.includes('KURDISH:') && content.includes('PERSIAN:')) {
        const parts = content.split('PERSIAN:');
        kurdishText = parts[0].replace('KURDISH:', '').trim();
        persianText = parts[1].trim();
    } else {
        persianText = content.replace(/\n/g, ' ').trim();
    }

    return NextResponse.json({ kurdish: kurdishText, persian: persianText });
    
  } catch (e: any) {
    return NextResponse.json({ error: `Network: ${e.message}` }, { status: 502 });
  }
}
