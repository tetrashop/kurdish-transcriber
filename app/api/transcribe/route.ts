import { NextRequest, NextResponse } from 'next/server';

export const runtime = 'nodejs';
export const maxDuration = 30;

export async function POST(req: NextRequest) {
  const apiKey = process.env.GROQ_API_KEY;
  if (!apiKey) return NextResponse.json({ error: 'GROQ_API_KEY missing' }, { status: 500 });

  const form = await req.formData();
  const file = form.get('file');
  if (!(file instanceof Blob)) return NextResponse.json({ error: 'audio file missing' }, { status: 400 });

  // ۱. تبدیل صدا به متن (رونویسی)
  const upstream = new FormData();
  upstream.append('file', file, 'chunk.wav');
  upstream.append('model', 'whisper-large-v3');
  upstream.append('language', 'fa'); 
  // این پرامپت به Whisper کمک می‌کند تا کلمات فارسی بی‌ربط تولید نکند
  upstream.append('prompt', 'ئەمە گفتوگۆیەکی کوردییە. تکایە بە زمانی کوردی بنووسە.'); 
  upstream.append('response_format', 'json');
  upstream.append('temperature', '0');

  try {
    const sttRes = await fetch('https://api.groq.com/openai/v1/audio/transcriptions', {
      method: 'POST',
      headers: { Authorization: `Bearer ${apiKey}` },
      body: upstream,
    });
    
    if (!sttRes.ok) throw new Error(`STT Error: ${sttRes.status}`);
    const sttData = await sttRes.json();
    let originalText = sttData.text?.trim() || '';

    // فیلتر کردن توهم‌زنی‌های رایج Whisper (مثل موسیقی، زیرنویس و...)
    const hallucinations = ['موسیقی', 'Music', 'زیرنویس', 'ترجمه', 'Thank you', 'شکرا'];
    if (hallucinations.some(h => originalText.includes(h)) && originalText.length < 20) {
        return NextResponse.json({ kurdish: '', persian: '' }); // نادیده گرفتن این تکه
    }

    if (!originalText) return NextResponse.json({ kurdish: '', persian: '' });

    // ۲. اصلاح و ترجمه با مدل Llama (نسخه سریع و پایدار)
    const llmRes = await fetch('https://api.groq.com/openai/v1/chat/completions', {
      method: 'POST',
      headers: { 
        Authorization: `Bearer ${apiKey}`,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        model: 'llama-3.1-8b-instant', // مدل بسیار مطمئن برای JSON
        messages: [
          { 
            role: 'system', 
            content: 'You are a Kurdish (Sorani) to Persian translator. The input is generated by speech recognition and may contain phonetic errors. Guess the intended Kurdish text, write the correct Kurdish text, and translate it to fluent Persian. Output ONLY valid JSON strictly in this format: {"kurdish": "...", "persian": "..."}' 
          },
          { role: 'user', content: originalText }
        ],
        response_format: { type: "json_object" },
        temperature: 0.1,
      }),
    });

    if (!llmRes.ok) {
        return NextResponse.json({ kurdish: originalText, persian: 'ترجمه در دسترس نیست' });
    }

    const llmData = await llmRes.json();
    let content = llmData.choices[0].message.content;
    
    // پاک کردن علامت‌های مارک‌داون (اگر مدل اضافه کرده باشد)
    content = content.replace(/```json/g, '').replace(/```/g, '').trim();

    try {
        const parsed = JSON.parse(content);
        return NextResponse.json({ kurdish: parsed.kurdish || originalText, persian: parsed.persian || '' });
    } catch (parseError) {
        // اگر باز هم خطا داد، فقط متن اصلی را برگردان
        return NextResponse.json({ kurdish: originalText, persian: 'ترجمه ناموفق بود' });
    }
    
  } catch (e: any) {
    return NextResponse.json({ error: `Network: ${e.message}` }, { status: 502 });
  }
}
